"""Cut the app recording into per-line clips, timed to the voiceover.

Each clip spans its voiceover line (line start to the next line's start) and is
sped up to fit. Frames land in clips/<line>-<n>/ as JPEGs (not committed);
clips.js tells pitch.html where each clip sits on the timeline.

  python clips.py path/to/recording.webm
"""
import json
import re
import shutil
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).parent
src = sys.argv[1]
spec = json.loads((HERE / "clips.json").read_text())
timing = json.loads(re.search(r"window\.TIMING = (.*);", (HERE / "timing.js").read_text(), re.S).group(1))
order = [l for l in timing["lines"]]
fps = spec["fps"]


def span(line_id):
    i = order.index(line_id)
    start = timing["lines"][line_id]["start"]
    nxt = order[i + 1] if i + 1 < len(order) else None
    scene = timing["lines"][line_id]["scene"]
    if nxt and timing["lines"][nxt]["scene"] == scene:
        end = timing["lines"][nxt]["start"]
    else:
        end = next(s["end"] for s in timing["scenes"] if s["id"] == scene)
    return start, end


out = []
shutil.rmtree(HERE / "clips", ignore_errors=True)
for clip in spec["clips"]:
    start, end = span(clip["line"])
    total = end - start
    shares = [c[2] if len(c) > 2 else None for c in clip["cuts"]]
    if None in shares:
        lens = [c[1] - c[0] for c in clip["cuts"]]
        shares = [l / sum(lens) for l in lens]
    t = start
    for n, (cut, share) in enumerate(zip(clip["cuts"], shares)):
        a, b = cut[0], cut[1]
        dur = total * share
        speed = (b - a) / dur
        d = HERE / "clips" / f"{clip['line']}-{n}"
        d.mkdir(parents=True)
        subprocess.run([
            "ffmpeg", "-loglevel", "error", "-ss", str(a), "-to", str(b), "-i", src,
            "-vf", f"setpts=(PTS-STARTPTS)/{speed:.5f},fps={fps},scale=1600:900:flags=lanczos",
            "-q:v", "3", str(d / "%05d.jpg"),
        ], check=True)
        frames = len(list(d.glob("*.jpg")))
        out.append({"line": clip["line"], "dir": f"clips/{d.name}", "start": round(t, 3), "dur": round(dur, 3), "frames": frames, "speed": round(speed, 2)})
        print(f"{d.name:8} {t:7.2f}+{dur:5.2f}s  speed {speed:4.2f}x  {frames} frames")
        t += dur
(HERE / "clips.js").write_text("// Generated by clips.py. Do not edit.\nwindow.CLIPS = " + json.dumps(out, indent=1) + ";\n")
