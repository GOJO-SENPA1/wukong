"""Voiceover for the pitch video: speaks pitch/script.json with Piper and lays it on a timeline.

Reuses the film's helpers (../voice.py). Writes:
  timing.js   window.TIMING: scene and line times, read by pitch.html (committed)
  vo/vo.wav   the voiceover at 48 kHz
  ../../docs/media/wukong-pitch.srt   subtitles

  python voice.py --model en-us-ryan-high.onnx [--piper path/to/piper]
"""
import argparse
import json
import sys
from pathlib import Path

import numpy as np
from scipy.io import wavfile

HERE = Path(__file__).parent
sys.path.insert(0, str(HERE.parent))
from voice import SR, synth, trim, word_times  # noqa: E402


def srt_time(t):
    ms = int(round(t * 1000))
    h, ms = divmod(ms, 3_600_000)
    m, ms = divmod(ms, 60_000)
    s, ms = divmod(ms, 1000)
    return f"{h:02}:{m:02}:{s:02},{ms:03}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--model", required=True)
    ap.add_argument("--piper", default="piper")
    args = ap.parse_args()

    script = json.loads((HERE / "script.json").read_text())
    v = script["voice"]
    t = v["lead"]
    track, lines, scenes = [], {}, []
    for scene in script["scenes"]:
        s_start = t
        for line in scene["lines"]:
            a = trim(synth(args.piper, args.model, line.get("say", line["text"]), v["lengthScale"]))
            words = word_times(line["text"], a)
            lines[line["id"]] = {
                "scene": scene["id"], "text": line["text"],
                "start": round(t, 3), "end": round(t + len(a) / SR, 3),
                "words": [{**w, "t0": round(t + w["t0"], 3), "t1": round(t + w["t1"], 3)} for w in words],
            }
            track.append((t, a))
            t += len(a) / SR + v["gapAfterLine"] + line.get("hold", 0)
            print(f"{line['id']:>4}  {lines[line['id']]['start']:6.2f}–{lines[line['id']]['end']:6.2f}  {line['text']}")
        t += v["gapAfterScene"] - v["gapAfterLine"]
        scenes.append({"id": scene["id"], "start": round(s_start, 3)})
    duration = round(t + v["tail"], 3)
    for i, s in enumerate(scenes):
        s["end"] = scenes[i + 1]["start"] if i + 1 < len(scenes) else duration

    out = np.zeros(int(duration * SR) + SR, dtype=np.float32)
    for start, a in track:
        i = int(start * SR)
        out[i : i + len(a)] += a
    out = out[: int(duration * SR)]
    out *= 0.89 / max(1e-6, np.abs(out).max())
    (HERE / "vo").mkdir(exist_ok=True)
    wavfile.write(HERE / "vo" / "vo.wav", SR, (out * 32767).astype(np.int16))

    timing = {"duration": duration, "scenes": scenes, "lines": lines}
    (HERE / "timing.js").write_text("// Generated by voice.py. Do not edit.\nwindow.TIMING = " + json.dumps(timing, ensure_ascii=False, indent=1) + ";\n")

    media = HERE.parent.parent / "docs" / "media"
    media.mkdir(parents=True, exist_ok=True)
    cues = [f"{i}\n{srt_time(l['start'])} --> {srt_time(l['end'] + 0.25)}\n{l['text']}\n" for i, l in enumerate(lines.values(), 1)]
    (media / "wukong-pitch.srt").write_text("\n".join(cues))
    print(f"duration {duration:.2f}s → vo/vo.wav, timing.js, docs/media/wukong-pitch.srt")


if __name__ == "__main__":
    main()
